// Isolated fixture: verify streamed quotes without running models or changing replay accounts.
const {chromium,expect}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base='http://127.0.0.1:8011';
async function api(path,body){const response=await fetch(base+path,body===undefined?{}:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});assert(response.ok,path);return response.json();}
(async()=>{
  const identity=await api('/__test__/identity');assert(identity.fixture&&!identity.real_models&&!identity.external_network);
  const initial=await api('/api/state'),dates=initial.dates;
  await api('/api/matches',{mode:'replay',start:dates[30],end:dates[33],models:['deepseek-flash'],title:'TEST FIXTURE historical isolation'});
  const before=await api('/api/state'),errors=[],flows=[];
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:800}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',async route=>{if(/^https?:/.test(route.request().url())&&new URL(route.request().url()).origin!==base){errors.push('external browser request');await route.abort();}else await route.continue();});
  try{
    await page.goto(base+'/#overview');
    await expect(page.locator('#live-overview')).toBeVisible();
    await expect(page.locator('#dashboard-view')).toBeHidden();
    await expect(page.locator('#chart-period')).not.toBeVisible();
    await expect(page.locator('#live-stock-price')).not.toHaveText('—');
    flows.push('homepage-live-quotes-independent-of-replay-progress');
    const oldPrice=await page.locator('#live-stock-price').innerText();
    const oldPlot=await page.locator('#live-price-chart').evaluate(canvas=>canvas.toDataURL());
    const tick=await api('/__test__/market-tick',{});
    await expect(page.locator('#live-stock-price')).not.toHaveText(oldPrice);
    await expect(page.locator('#live-quote-time')).toHaveText(tick.quotes.find(q=>q.symbol==='sh000300').time.slice(0,19).replace('T',' '));
    await expect.poll(()=>page.locator('#live-price-chart').evaluate(canvas=>canvas.toDataURL())).not.toBe(oldPlot);
    flows.push('server-event-updates-price-time-and-chart-without-page-reload');
    await page.locator('[data-market-chart="samples"]').click();
    await expect(page.locator('[data-market-chart="samples"]')).toHaveAttribute('aria-pressed','true');
    const detail=await api('/api/market/stocks/sh000300');
    await api('/api/market/live?refresh=true');
    assert.equal((await api('/api/market/stocks/sh000300')).samples.length,detail.samples.length);
    flows.push('sampling-records-only-provider-ticks');
    const validPrice=await page.locator('#live-stock-price').innerText();
    await api('/__test__/market-tick',{error:true});
    await expect(page.locator('#live-market-error')).toContainText('暂时不可用');
    await expect(page.locator('#live-stock-price')).toHaveText(validPrice);
    await expect(page.locator('#live-quote-note')).toContainText('保留旧值');
    flows.push('provider-failure-keeps-quote-and-discloses-staleness');
    await api('/__test__/market-tick',{});
    await expect(page.locator('#live-market-error')).toBeHidden();
    flows.push('provider-recovery-clears-error');
    await page.locator('[data-stock-row="sh600519"]').click();
    await expect(page.locator('#live-stock-name')).toHaveText('贵州茅台');
    await expect(page.locator('#live-stock-facts')).toContainText('今开');
    flows.push('stock-selection-updates-detail-fields');
    await page.locator('#live-stock-query').fill('600001');
    await page.locator('#live-stock-search button').click();
    await expect(page.locator('[data-add-stock="sh600001"]')).toBeVisible();
    await page.locator('[data-add-stock="sh600001"]').click();
    await expect(page.locator('[data-stock-row="sh600001"]')).toBeVisible();
    await expect(page.locator('#live-stock-symbol')).toHaveText('sh600001');
    await page.reload();
    await expect(page.locator('[data-stock-row="sh600001"]')).toBeVisible();
    await expect(page.locator('#live-stock-symbol')).toHaveText('sh600001');
    flows.push('arbitrary-ashare-search-add-and-reload-persistence');
    await page.locator('[data-unwatch="sh600001"]').click();
    await expect(page.locator('[data-stock-row="sh600001"]')).toHaveCount(0);
    await expect(page.locator('#live-stock-name')).toHaveText('沪深300');
    flows.push('remove-self-selected-stock-restores-valid-selection');
    await page.locator('#navigation [data-view="history"]').click();
    await expect(page.locator('#dashboard-view')).toBeVisible();
    await expect(page.locator('#live-overview')).toBeHidden();
    await expect(page.locator('#market-strip')).toContainText('历史行情');
    await page.locator('#navigation [data-view="overview"]').click();
    await expect(page.locator('#market-strip')).toContainText('实时行情');
    flows.push('history-and-live-market-display-remain-distinct');
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    fs.mkdirSync('test-results',{recursive:true});
    await page.screenshot({path:'test-results/live-market-mobile-fixture.png',fullPage:true});
    flows.push('mobile-market-layout-no-page-overflow');
    const after=await api('/api/state');assert.equal(after.id,before.id);assert.equal(after.round,before.round);assert.deepEqual(after.players,before.players);assert.equal(after.runtime.calls,before.runtime.calls);assert.deepEqual(errors,[]);
    flows.push('historical-accounts-and-strategies-preserved-no-model-calls');
    console.log(JSON.stringify({passed:true,fixture:true,flows,errors,real_model_calls:0}));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
